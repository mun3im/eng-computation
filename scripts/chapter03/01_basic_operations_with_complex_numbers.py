"""
Numbers, Variables and Units - Beyond Simple Numbers
Subsection: Basic Operations with Complex Numbers
"""

c1 = 3 + 4j
c2 = 1 - 2j

# Addition
print(c1 + c2)  # Output: (4+2j)

# Subtraction
print(c1 - c2)  # Output: (2+6j)

# Multiplication
print(c1 * c2)  # Output: (11-2j)

# Division
print(c1 / c2)  # Output: (-1+2j)
